function createReadme(manifest: ComposerManifest) {
  return `# ${manifest.application.name}\n\nGenerated by WebBlueprint Export Engine v0.\n\n## Run\n\n\`\`\`bash\nnpm ci\nnpm run dev\n\`\`\`\n\n## Verify\n\n\`\`\`bash\nnpm run build\n\`\`\`\n\nThe generation source is preserved in \`webblueprint.json\`.\n`;
}

export function buildReactExportProject(manifest: ComposerManifest): ExportProject {
  assertExportableManifest(manifest);

  const files: ExportProjectFile[] = [
    { path: '.gitignore', content: 'node_modules\ndist\n.DS_Store\n' },
    { path: 'README.md', content: createReadme(manifest) },
    { path: 'index.html', content: indexHtml },
    { path: 'package-lock.json', content: createPackageLock(manifest) },
    { path: 'package.json', content: createPackageJson(manifest) },
    { path: 'src/App.tsx', content: appSource },
    { path: 'src/generated/application.ts', content: createGeneratedApplication(manifest) },
    { path: 'src/main.tsx', content: mainSource },
    { path: 'src/styles.css', content: styleSource },
    { path: 'tsconfig.json', content: tsconfig },
    { path: 'vite.config.ts', content: viteConfig },
    { path: 'webblueprint.json', content: `${JSON.stringify(manifest, null, 2)}\n` },
  ];

  return { rootName: projectPackageName(manifest.application.slug), files };
}

export function buildReactExportZip(manifest: ComposerManifest) {
  const project = buildReactExportProject(manifest);
  return { fileName: `${project.rootName}.zip`, bytes: createStoredZip(project.files) };
}

export function downloadReactExportZip(manifest: ComposerManifest) {
  const { bytes, fileName } = buildReactExportZip(manifest);
  const arrayBuffer = bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength) as ArrayBuffer;
  const blob = new Blob([arrayBuffer], { type: 'application/zip' });
  const objectUrl = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = objectUrl;
  link.download = fileName;
  link.click();
  URL.revokeObjectURL(objectUrl);
}
