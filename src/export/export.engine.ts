type PackageTemplate = {
  dependencies: Record<string, string>;
  devDependencies: Record<string, string>;
  engines?: Record<string, string>;
};

type PackageLockTemplate = {
  name?: string;
  version?: string;
  packages?: Record<string, { name?: string; version?: string }>;
};

const packageTemplate = JSON.parse(packageJsonTemplateText) as PackageTemplate;

function projectPackageName(slug: string) {
  return slug.replace(/[^a-z0-9-]/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '') || 'webblueprint-app';
}

function assertExportableManifest(manifest: ComposerManifest) {
  if (!manifest.application.name.trim()) {
    throw new Error('Cannot export an application without a name.');
  }

  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(manifest.application.slug)) {
    throw new Error('Cannot export an application with an invalid slug.');
  }

  const pageIds = new Set(manifest.pages.map((page) => page.id));
  if (manifest.navigation.items.some((item) => !pageIds.has(item.pageId))) {
    throw new Error('Navigation references a page that is not included in the export.');
  }
}

function createPackageJson(manifest: ComposerManifest) {
  return `${JSON.stringify(
    {
      name: projectPackageName(manifest.application.slug),
      private: true,
      version: '0.1.0',
      type: 'module',
      engines: packageTemplate.engines,
      scripts: {
        dev: 'vite',
        build: 'tsc --noEmit && vite build',
        preview: 'vite preview',
      },
      dependencies: packageTemplate.dependencies,
      devDependencies: packageTemplate.devDependencies,
    },
    null,
    2,
  )}\n`;
}

function createPackageLock(manifest: ComposerManifest) {
  const packageName = projectPackageName(manifest.application.slug);
  const lock = JSON.parse(packageLockTemplateText) as PackageLockTemplate;
  lock.name = packageName;
  lock.version = '0.1.0';

  const rootPackage = lock.packages?.[''];
  if (rootPackage) {
    rootPackage.name = packageName;
    rootPackage.version = '0.1.0';
  }

  return `${JSON.stringify(lock, null, 2)}\n`;
}

function createGeneratedApplication(manifest: ComposerManifest) {
  return `export const application = ${JSON.stringify(manifest, null, 2)} as const;\n`;
}

